'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const app=fs.readFileSync('static/app.js','utf8');
const vars=new Map();
const context={prefs:{background:'#123456',panel:'#334455'},document:{documentElement:{style:{setProperty:(k,v)=>vars.set(k,v),removeProperty:k=>vars.delete(k)}}}};
vm.createContext(context);
const helpers=app.slice(app.indexOf('const colorVars='),app.indexOf('function applyAccent()'));
vm.runInContext(helpers,context);
vm.runInContext('applyCustomColors()',context);
assert.equal(vars.get('--bg'),'#123456');
assert.equal(vars.get('--panel'),'#334455');
assert.equal(vars.get('--input'),'#123456');
context.prefs={};vm.runInContext('applyCustomColors()',context);
assert.equal(vars.size,0,'reset removes overrides so theme defaults work');
assert.equal(vm.runInContext("pickerHex('rgb(21, 26, 23)')",context),'#151a17');
assert.equal(vm.runInContext("pickerHex('#abcdef')",context),'#abcdef');
console.log('Appearance override/reset and color-picker conversion checks passed.');

const topology=fs.readFileSync('static/topology.js','utf8');
const start=topology.indexOf('function connectionPoints(');
const end=topology.indexOf('function svg(',start);
vm.runInContext(topology.slice(start,end),context);
context.edge={points:[[50,60],[90,60]]};
context.a={x:0,y:0,width:20,height:20};context.b={x:100,y:100,width:20,height:20};
context.prefs.connection_mode='diagram';
assert.equal(vm.runInContext('connectionPoints(edge,a,b).length',context),4);
context.prefs.connection_mode='straight';
assert.equal(vm.runInContext('connectionPoints(edge,a,b).length',context),2);
assert.deepEqual(context.edge.points,[[50,60],[90,60]],'straight mode preserves original waypoints');
context.prefs.connection_mode='diagram';
assert.equal(vm.runInContext('connectionPoints(edge,a,b).length',context),4);
console.log('Connection toggle restores diagram waypoints without changing stored geometry.');
